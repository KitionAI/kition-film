import { test, expect, holdWorkerReply } from './fixtures.mjs'

for (const choice of ['clear', 'another clip']) {
  test(`F63 changing selection to ${choice} cancels a pending text editor without editing the former title`, async ({ film, page }) => {
    await film.open()
    await film.command('file.newProject', { name: 'Pending text selection' })
    await film.command('file.newSequence', { name: 'Titles', width: 640, height: 360, fps: 24, video: 2, audio: 0 })
    const { clip: first } = await film.command('graphics.newText', { text: 'First title', position: [80, 100], size: 40, newClip: true })
    const { clip: second } = await film.command('graphics.newText', { text: 'Second title', position: [80, 200], size: 40, newClip: true })
    await film.command('timeline.select', { clips: [first] })
    await film.focus()
    await page.keyboard.press("ControlOrMeta+Alt+'")
    const field = film.kit.getByTestId('film-program-text-edit')
    await expect(field).toHaveValue('First title')
    await field.press('Escape')
    const gate = await holdWorkerReply(film, 'graphicLayers')
    await film.focus()
    await page.keyboard.press("ControlOrMeta+Alt+'")
    await gate.wait()
    const selected = choice === 'clear' ? [] : [second]
    await film.command('timeline.select', { clips: selected })
    const history = await film.history()
    await gate.release()
    await expect(field).toHaveCount(0)
    expect((await film.sequence()).selection).toEqual(selected)
    expect(await film.history()).toEqual(history)
    expect((await film.command('graphics.list', { clip: first })).layers[0].text).toBe('First title')
    expect((await film.command('graphics.list', { clip: second })).layers[0].text).toBe('Second title')
    await film.command('timeline.select', { clips: [second] })
    await film.focus()
    await page.keyboard.press("ControlOrMeta+Alt+'")
    await expect(field).toHaveValue('Second title')
    await field.fill('Fresh edit')
    await field.press('Escape')
    await expect.poll(async () => (await film.command('graphics.list', { clip: second })).layers[0].text).toBe('Fresh edit')
    await film.undo()
    await expect.poll(async () => (await film.command('graphics.list', { clip: second })).layers[0].text).toBe('Second title')
    await film.redo()
    await film.saveReopen()
    expect((await film.command('graphics.list', { clip: second })).layers[0].text).toBe('Fresh edit')
  })
}
