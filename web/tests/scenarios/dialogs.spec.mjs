import { test, expect, holdWorkerCall, clips, editState, TICKS } from './fixtures.mjs'

for (const interruption of ['new project', 'new sequence', 'permissions']) {
  test(`F16 pending Sequence Settings cannot open after ${interruption}`, async ({ film }) => {
    await film.open()
    const gate = await holdWorkerCall(film, 'dialogDefaults')
    await film.kit.getByTestId('film-menu-Sequence').click()
    await film.kit.getByRole('menuitem', { name: 'Sequence Settings…', exact: true }).click()
    await gate.wait()
    if (interruption === 'permissions') {
      await film.configure({ disable: ['command:sequence.settings'] })
      await film.configure({ disable: [] })
    } else {
      if (interruption === 'new project') await film.command('file.newProject', { name: 'Replacement' })
      await film.command('file.newSequence', { name: 'Replacement sequence', width: 64, height: 36, fps: 24 })
    }
    const before = await film.details()
    const history = await film.history()
    await gate.release()
    await expect(film.kit.getByTestId('film-dialog-sequenceSettings')).toHaveCount(0)
    expect(await film.details()).toEqual(before)
    expect(await film.history()).toEqual(history)
  })
}

async function settings(film) {
  await film.kit.getByTestId('film-menu-Sequence').click()
  await film.kit.getByRole('menuitem', { name: 'Sequence Settings…', exact: true }).click()
  await expect(film.kit.getByTestId('film-dialog-sequenceSettings')).toBeVisible()
}

test('F22 an older dialog read cannot replace the newer dialog or discard its typed draft', async ({ film }) => {
  await film.open()
  const history = await film.history()
  const before = await film.sequence()
  const gate = await holdWorkerCall(film, 'dialogDefaults')
  await film.menu('sequence.settings')
  await gate.wait()
  await film.menu('file.newSequence')
  await expect(film.kit.getByRole('heading', { name: 'New Sequence', exact: true })).toBeVisible()
  const name = film.kit.getByTestId('film-dialog-sequenceSettings-name')
  await name.fill('Keep the newer draft')
  await gate.release()
  await expect(film.kit.getByRole('heading', { name: 'New Sequence', exact: true })).toBeVisible()
  await expect(name).toHaveValue('Keep the newer draft')
  await film.kit.getByTestId('film-dialog-cancel').click()
  await expect(film.kit.getByTestId('film-dialog')).toHaveCount(0)
  expect(await film.sequence()).toEqual(before)
  expect(await film.history()).toEqual(history)
})

test('F18 Sequence Settings previews without modifying the project; Cancel and one-step OK preserve history', async ({ film }) => {
  await film.open()
  const before = await film.sequence()
  const history = await film.history()
  const change = async () => {
    await film.kit.getByTestId('film-dialog-sequenceSettings-name').fill('场景 A · Scene A')
    await film.kit.getByTestId('film-dialog-sequenceSettings-width').locator('input').fill('640')
    await film.kit.getByTestId('film-dialog-sequenceSettings-height').locator('input').fill('360')
    await film.kit.getByTestId('film-dialog-sequenceSettings-height').locator('input').press('Tab')
    await expect.poll(() => film.frame().evaluate(async () => (await window.filmPreview.inspect())?.sequence?.settings?.width)).toBe(640)
    expect(await film.sequence()).toEqual(before)
    expect(await film.history()).toEqual(history)
  }
  await settings(film)
  await change()
  await film.kit.getByTestId('film-dialog-cancel').click()
  await expect(film.kit.getByTestId('film-dialog-sequenceSettings')).toHaveCount(0)
  expect(await film.sequence()).toEqual(before)
  expect(await film.history()).toEqual(history)
  await settings(film)
  await change()
  await film.kit.getByTestId('film-dialog-ok').click()
  await expect.poll(async () => (await film.sequence()).settings.width).toBe(640)
  const after = await film.sequence()
  expect(after.settings.height).toBe(360)
  expect(after.name).toBe('场景 A · Scene A')
  expect((await film.history()).undo).toHaveLength(history.undo.length + 1)
  await film.undo()
  await expect.poll(async () => (await film.sequence()).settings).toEqual(before.settings)
  await film.redo()
  await expect.poll(async () => (await film.sequence()).settings).toEqual(after.settings)
  await film.saveReopen()
  expect((await film.sequence()).settings).toEqual(after.settings)
  expect((await film.sequence()).name).toBe(after.name)
})

test('F19 Speed Duration ripple changes linked picture and sound and moves the following clip once', async ({ film }) => {
  await film.open()
  await film.command('file.newProject', { name: 'Three shots' })
  await film.command('file.newSequence', { name: '24 fps', width: 64, height: 36, fps: 24, video: 1, audio: 1 })
  const { item } = await film.command('file.newBarsAndTone', { seconds: 4 })
  for (let second = 0; second < 3; second += 1) await film.command('timeline.place', { item, seconds: second, sourceIn: TICKS, duration: TICKS })
  const before = await film.sequence()
  await film.command('timeline.select', { clips: [clips(before)[1].clip] })
  const history = await film.history()
  await film.kit.getByTestId('film-menu-Clip').click()
  await film.kit.getByTestId('film-cmd-clip.speedDuration').click()
  await film.kit.getByTestId('film-dialog-speedDuration-speed').locator('input').fill('50')
  await film.kit.getByTestId('film-dialog-speedDuration-ripple').check()
  await film.kit.getByTestId('film-dialog-ok').click()
  await expect.poll(async () => (await film.sequence()).duration).toBe(4 * TICKS)
  const after = await film.sequence()
  for (const kind of ['video', 'audio']) {
    expect(clips(after, kind).map(clip => [clip.startFrame, clip.durationFrames])).toEqual([[0, 24], [24, 48], [72, 24]])
    expect(clips(after, kind)[1].speed).toBe(0.5)
  }
  expect((await film.history()).undo).toHaveLength(history.undo.length + 1)
  await film.undo()
  await expect.poll(async () => editState(await film.sequence())).toEqual(editState(before))
  await film.redo()
  await expect.poll(async () => editState(await film.sequence())).toEqual(editState(after))
  await film.saveReopen()
  expect(editState(await film.sequence())).toEqual(editState(after))
})
