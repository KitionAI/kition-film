import { test, expect, clips, editState, TICKS } from './fixtures.mjs'

test('F17 a huge forward frame step never wraps backward and the editor remains usable', async ({ film }) => {
  await film.open()
  await film.command('playhead.set', { frame: 2400 })
  const before = await film.details()
  await film.command('playhead.step', { frames: 9_223_372_036_854_775_000 })
  expect((await film.details()).playhead).toBeGreaterThanOrEqual(before.playhead)
  await film.command('playhead.set', { frame: 24 })
  await film.command('sequence.addEdit', {})
  expect(clips(await film.sequence())).toHaveLength(2)
  await film.undo()
  await expect.poll(async () => editState(await film.sequence())).toEqual(editState(before.sequence))
})

test('F01 razor splits linked picture and sound; undo, redo and save/reopen preserve the edit', async ({ film, page }) => {
  await film.open()
  const before = await film.sequence()
  const clip = clips(before)[0]
  const box = await film.kit.getByTestId(`film-clip-${clip.clip}`).boundingBox()
  await film.focus()
  await page.keyboard.press('c')
  await expect(film.kit.getByTestId('film-tools')).toHaveAttribute('data-active', 'Razor')
  await page.mouse.click(box.x + box.width * 0.5, box.y + box.height * 0.5)
  await expect.poll(async () => clips(await film.sequence()).length).toBe(clips(before).length + 1)
  const after = await film.sequence()
  expect(clips(after, 'audio')).toHaveLength(clips(before, 'audio').length + 1)
  expect(clips(after).reduce((sum, item) => sum + item.duration, 0)).toBe(clips(before).reduce((sum, item) => sum + item.duration, 0))
  await film.undo()
  await expect.poll(async () => editState(await film.sequence())).toEqual(editState(before))
  await film.redo()
  await expect.poll(async () => editState(await film.sequence())).toEqual(editState(after))
  await film.saveReopen()
  expect(editState(await film.sequence())).toEqual(editState(after))
})

test('F02 denied timeline move cannot mutate via pointer; lifting the restriction permits a fresh gesture', async ({ film, page }) => {
  await film.open()
  const before = await film.sequence()
  const clip = clips(before)[0]
  const drag = async () => {
    const box = await film.kit.getByTestId(`film-clip-${clip.clip}`).boundingBox()
    await page.mouse.move(box.x + box.width * 0.45, box.y + 10)
    await page.mouse.down()
    await page.mouse.move(box.x + box.width * 0.45 + 75, box.y + 10, { steps: 6 })
    await page.mouse.up()
  }
  await film.configure({ disable: ['command:timeline.move'] })
  await drag()
  await expect(film.kit.getByTestId('film-message')).toBeVisible()
  expect(editState(await film.sequence())).toEqual(editState(before))
  await film.configure({ disable: [] })
  await drag()
  await expect.poll(async () => clips(await film.sequence()).find(item => item.clip === clip.clip)?.start).not.toBe(clip.start)
})

test('F03 revoking then restoring move permission cancels the held drag', async ({ film, page }) => {
  await film.open()
  const before = await film.sequence()
  const clip = clips(before)[0]
  const box = await film.kit.getByTestId(`film-clip-${clip.clip}`).boundingBox()
  await page.mouse.move(box.x + box.width * 0.45, box.y + 10)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * 0.45 + 75, box.y + 10, { steps: 6 })
  await film.configure({ disable: ['command:timeline.move'] })
  await film.configure({ disable: [] })
  await page.mouse.up()
  // A subsequent command flushes queued pointer commands before inspecting the document.
  await film.command('playhead.set', { seconds: 0 })
  expect(editState(await film.sequence())).toEqual(editState(before))
})

