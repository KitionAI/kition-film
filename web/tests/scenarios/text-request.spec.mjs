import { test, expect, holdWorkerCall } from './fixtures.mjs'

test('F24 permission interruption cancels pending Begin Text Editing', async ({ film, page }) => {
  await film.open()
  await film.command('file.newProject', { name: 'Pending text editing' })
  await film.command('sequence.new', { name: 'Title', width: 640, height: 360, fps: 24, video: 1, audio: 0 })
  const { clip } = await film.command('graphics.newText', { text: 'Keep this title', position: [160, 100], size: 40 })
  await film.command('timeline.select', { clips: [clip] })
  // Opening and closing a real editing session also drains its initial layer reads.
  await film.focus()
  await page.keyboard.press("ControlOrMeta+Alt+'")
  const field = film.kit.getByTestId('film-program-text-edit')
  await expect(field).toHaveValue('Keep this title')
  await field.press('Escape')
  const gate = await holdWorkerCall(film, 'graphicLayers')
  await film.focus()
  await page.keyboard.press("ControlOrMeta+Alt+'")
  await gate.wait()
  await film.configure({ disable: ['command:graphics.beginTextEditing', 'command:graphics.setText'] })
  await film.configure({ disable: [] })
  const history = await film.history()
  await gate.release()
  await expect(field).toHaveCount(0)
  expect(await film.history()).toEqual(history)
  expect((await film.command('graphics.list', { clip })).layers[0].text).toBe('Keep this title')
  await film.focus()
  await page.keyboard.press("ControlOrMeta+Alt+'")
  await expect(field).toHaveValue('Keep this title')
  await field.press('Escape')
})
